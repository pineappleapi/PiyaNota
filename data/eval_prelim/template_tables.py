"""Fill the user's 'Camera-Captured vs. Digital Input' template from runs/results.json.

Delta = Camera - Digital in percentage points (SER: positive = worse on camera; accuracy: negative = worse).
Staff detection = pooled recall over the in-scope pages; it depends only on the Stage 1/2 code, so it is
shared by all models run through the same pipeline.
Usage (repo root):  python data/eval_prelim/template_tables.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = json.loads((HERE / "runs" / "results.json").read_text(encoding="utf-8"))
MODELS = [("Base CRNN, original pipeline", "base"),
          ("Fine-tuned seed1, no classifier", "finetuned"), ("Fine-tuned seed2, no classifier", "finetuned"),
          ("Fine-tuned seed1 + clef/key classifier", "finetuned"),
          ("Fine-tuned seed2 + clef/key classifier", "finetuned")]
PAIRED = ["non_nobis_domine", "gaano_ko_ikaw_kamahal"]


def staff(cond: str, pipe: str, pieces: list[str]) -> float:
    m = g = 0
    for p in pieces:
        e = R[f"{cond}/{p}"]
        s = (e["staff"] if "staff" in e else e)[pipe]
        m, g = m + s["matched"], g + s["gt_staves"]
    return m / g


def pooled(cond: str, model: str, pieces: list[str]) -> tuple[float, float]:
    te = nr = ok = n = 0
    for p in pieces:
        d = R[f"{cond}/{p}"]["models"][model]
        te, nr, ok, n = te + d["tok_err"], nr + d["n_ref"], ok + d["sow_ok"], n + d["sow_n"]
    return te / nr, ok / n


def block(title: str, pieces: list[str], staff_pieces: list[str]) -> list[str]:
    out = [f"### {title}", "", "| Model | Input | Staff detection (recall) | SER | Pitch accuracy |",
           "|---|---|---|---|---|"]
    for model, pipe in MODELS:
        vals = {}
        for cond in ("digital", "camera"):
            ser, acc = pooled(cond, model, pieces)
            vals[cond] = (staff(cond, pipe, staff_pieces), ser, acc)
        d, c = vals["digital"], vals["camera"]
        out.append(f"| {model} | Digital | {d[0]:.1%} | {d[1]:.1%} | {d[2]:.1%} |")
        out.append(f"| | Camera | {c[0]:.1%} | {c[1]:.1%} | {c[2]:.1%} |")
        out.append("| | **Δ (pp)** | " + " | ".join(f"**{(c[i] - d[i]) * 100:+.1f}**" for i in range(3)) + " |")
    return out + [""]


def main() -> None:
    lines = ["# Camera-Captured vs. Digital Input (template fill; generated by template_tables.py)", "",
             "Test set: Non Nobis Domine pp.1-3 + Gaano Ko Ikaw Kamahal pp.1-9 (both FROZEN in the Stage 1 mask "
             "split, author-verified GT, digital PDF + phone photo of each page). Non Nobis p4 (solo staff) is "
             "out of scope and not scored.", "",
             "Δ = Camera − Digital, percentage points. SER lower is better; staff detection and pitch accuracy "
             "higher is better. Pitch accuracy ignores note duration. SER and pitch accuracy are end-to-end: "
             "staves lost at Stage 2 count as fully wrong.", ""]
    lines += block("Pooled: Non Nobis Domine pp.1-3 + Gaano Ko Ikaw Kamahal", PAIRED, PAIRED)
    lines += block("Non Nobis Domine pp.1-3 only", ["non_nobis_domine"], ["non_nobis_domine"])
    lines += block("Gaano Ko Ikaw Kamahal only", ["gaano_ko_ikaw_kamahal"], ["gaano_ko_ikaw_kamahal"])
    (HERE / "TEMPLATE_tables.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
